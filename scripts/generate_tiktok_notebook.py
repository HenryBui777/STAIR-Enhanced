    "            extract_dir = os.path.join(LOCAL_DATA, 'raw_tiktok')\n",
    "            with zipfile.ZipFile(repo_zip, 'r') as zf:\n",
    "                zf.extractall(extract_dir)\n",
    "            for root, dirs, files in os.walk(extract_dir):\n",
    "                if all(rf in files for rf in RAW_FILES):\n",
    "                    raw_src = root\n",
    "                    break\n",
    "\n",
    "        if raw_src:\n",
