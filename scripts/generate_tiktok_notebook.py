    "            bridge_directories(cand, TARGET_FOLDER)\n",
    "            return {'tiktok': target_processed}\n",
    "\n",
    "    # 2. Tìm kiếm trong /kaggle/input (hỗ trợ /kaggle/input/tiktok/tiktok, /kaggle/input/Tiktok/tiktok, ...)\n",
